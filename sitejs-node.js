function main() {
  const args = process.argv.slice(2);
  const command = args[0];

  if (!command || command === '--help' || command === '-h') {
    console.log(`
SiteJS.py Node.js Companion v${VERSION}

Usage:
  sitejs-node new <name>          Create a new site
  sitejs-node serve [--port P] [--host H]  Start development server
  sitejs-node build [--output D]  Build static site
  sitejs-node deploy              Deploy to target
  sitejs-node db <action> [key] [value]  Manage database
  sitejs-node --help              Show this help
  sitejs-node --version           Show version

Examples:
  sitejs-node new my-site
  cd my-site
  sitejs-node serve --port 8080
  sitejs-node build
  sitejs-node deploy

For more information, see SiteJavaScript.MD
    `);
    process.exit(0);
  }

  if (command === '--version' || command === '-v') {
    console.log(`sitejs-node v${VERSION}`);
    process.exit(0);
  }

  if (command === 'new') {
    const name = args[1];
    newSite(name);
    return;
  }

  if (command === 'serve') {
    let port = DEFAULT_PORT;
    let host = DEFAULT_HOST;
    for (let i = 1; i < args.length; i++) {
      if (args[i] === '--port' && args[i + 1]) {
        port = parseInt(args[i + 1], 10);
        i++;
      } else if (args[i] === '--host' && args[i + 1]) {
        host = args[i + 1];
        i++;
      }
    }
    ensureStructure();
    checkPython();
    installPythonDeps();
    serve(port, host);
    return;
  }

  if (command === 'build') {
    let output = 'dist';
    for (let i = 1; i < args.length; i++) {
      if ((args[i] === '--output' || args[i] === '-o') && args[i + 1]) {
        output = args[i + 1];
        i++;
      }
    }
    ensureStructure();
    checkPython();
    build(output);
    return;
  }

  if (command === 'deploy') {
    ensureStructure();
    checkPython();
    deploy();
    return;
  }

  if (command === 'db') {
    const action = args[1];
    const key = args[2];
    const value = args[3];
    if (!action) {
      console.log('❌ Please specify a database action: get, set, delete, all');
      process.exit(1);
    }
    ensureStructure();
    checkPython();
    db(action, key, value);
    return;
  }

  if (command === 'docs') {
    generateSiteJsDocs();
    return;
  }

  console.log(`❌ Unknown command: ${command}`);
  console.log('   Run sitejs-node --help for available commands');
  process.exit(1);
}

if (require.main === module) {
  main();
}

