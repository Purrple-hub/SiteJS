const DIRS = ['pages', 'public', 'templates', 'data', 'logs', 'dist'];

function ensureStructure() {
  for (const dir of DIRS) {
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
      console.log(`📁 Created: ${dir}/`);
    }
  }

  for (const [file, content] of Object.entries(TEMPLATES)) {
    if (!fs.existsSync(file)) {
      fs.writeFileSync(file, content, 'utf-8');
      console.log(`📄 Created: ${file}`);
    }
  }
}

function checkPython() {
  try {
    const result = exec('python3 --version', (err, stdout) => {
      if (err) {
        console.log('❌ Python 3 not found. Please install Python 3.9+');
        console.log('   https://www.python.org/downloads/');
        process.exit(1);
      }
      console.log(`✅ ${stdout.trim()}`);
    });
  } catch (e) {
    console.log('❌ Python 3 not found. Please install Python 3.9+');
    process.exit(1);
  }
}

function installPythonDeps() {
  console.log('📦 Installing Python dependencies...');
  const deps = ['markdown', 'jinja2', 'watchdog', 'cryptography'];
  exec(`pip3 install ${deps.join(' ')}`, (err, stdout, stderr) => {
    if (err) {
      console.log('⚠️  Failed to install Python deps. Run manually:');
      console.log(`   pip3 install ${deps.join(' ')}`);
    } else {
      console.log('✅ Python dependencies installed');
    }
  });
}

function checkSitePy() {
  const sitejsPath = path.join(__dirname, 'sitejs.py');
  if (!fs.existsSync(sitejsPath)) {
    console.log('❌ sitejs.py not found in current directory');
    console.log('   Please clone the repository or download sitejs.py');
    process.exit(1);
  }
  return sitejsPath;
}

function serve(port, host) {
  port = port || DEFAULT_PORT;
  host = host || DEFAULT_HOST;

  console.log(`🚀 Starting SiteJS.py server on http://${host}:${port}`);
  console.log(`   Press Ctrl+C to stop`);

  const python = process.platform === 'win32' ? 'python' : 'python3';
  const args = [checkSitePy(), 'serve', '--host', host, '--port', port];
  const proc = spawn(python, args, {
    stdio: 'inherit',
    cwd: process.cwd()
  });

  proc.on('error', (err) => {
    console.log('❌ Failed to start server:', err.message);
    process.exit(1);
  });

  proc.on('close', (code) => {
    if (code !== 0) {
      console.log(`❌ Server exited with code ${code}`);
    }
    process.exit(code);
  });

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
    terminal: true
  });

  rl.on('SIGINT', () => {
    console.log('\n🛑 Stopping server...');
    proc.kill('SIGINT');
    rl.close();
  });

  return proc;
}

function build(outputDir) {
  outputDir = outputDir || 'dist';
  console.log(`🏗️  Building static site to ${outputDir}/`);

  const python = process.platform === 'win32' ? 'python' : 'python3';
  const args = [checkSitePy(), 'build', '--output', outputDir];
  const proc = spawn(python, args, {
    stdio: 'inherit',
    cwd: process.cwd()
  });

  proc.on('error', (err) => {
    console.log('❌ Build failed:', err.message);
    process.exit(1);
  });

  proc.on('close', (code) => {
    if (code !== 0) {
      console.log(`❌ Build failed with code ${code}`);
      process.exit(code);
    }
    console.log('✅ Build complete!');
  });
}

