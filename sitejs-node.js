function db(action, key, value) {
  const python = process.platform === 'win32' ? 'python' : 'python3';
  const args = [checkSitePy(), 'db', action];
  if (key) args.push(key);
  if (value) args.push(value);

  const proc = spawn(python, args, {
    stdio: 'inherit',
    cwd: process.cwd()
  });

  proc.on('error', (err) => {
    console.log('❌ Database command failed:', err.message);
    process.exit(1);
  });

  proc.on('close', (code) => {
    if (code !== 0) {
      process.exit(code);
    }
  });
}

function newSite(name) {
  if (!name) {
    console.log('❌ Please provide a site name');
    console.log('   Usage: sitejs-node new <name>');
    process.exit(1);
  }

  if (fs.existsSync(name)) {
    console.log(`❌ Directory "${name}" already exists`);
    process.exit(1);
  }

  fs.mkdirSync(name, { recursive: true });
  const cwd = process.cwd();
  process.chdir(name);

  ensureStructure();

  process.chdir(cwd);

  console.log(`✅ Created new site: ${name}`);
  console.log(`   cd ${name}`);
  console.log('   sitejs-node serve');
}

